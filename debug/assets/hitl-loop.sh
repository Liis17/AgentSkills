#!/usr/bin/env bash
# Петля воспроизведения с человеком: агент запускает скрипт,
# пользователь выполняет шаги в своём терминале и отвечает на вопросы.
#
# Скопируй файл во временную папку вне репозитория, впиши шаги
# между отметками ниже и запусти: bash hitl-loop.sh
#
#   step "<действие>"            — показать действие и ждать Enter
#   ask  ИМЯ "<вопрос>"          — задать вопрос и сохранить ответ в ИМЯ
#
# В конце ответы печатаются строками ИМЯ=значение для разбора агентом.

set -euo pipefail

ANSWERS=()

step() {
  printf '\n>>> %s\n' "$1"
  read -r -p "    [Enter, когда готово] " _
}

ask() {
  local name="$1" question="$2" answer
  printf '\n>>> %s\n' "$question"
  read -r -p "    > " answer
  ANSWERS+=("$name=$answer")
}

# --- шаги: начало -------------------------------------------------------

step "Открой приложение по адресу http://localhost:3000 и войди в аккаунт."

ask FAILED "Нажми кнопку «Экспорт». Появилась ошибка? (да/нет)"

ask ERROR_TEXT "Вставь текст ошибки (или «нет»):"

# --- шаги: конец --------------------------------------------------------

printf '\n--- Ответы ---\n'
printf '%s\n' "${ANSWERS[@]}"
